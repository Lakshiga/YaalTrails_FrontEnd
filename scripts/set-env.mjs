// Turns .env into src/environments/env.generated.ts (both git-ignored), so keys never live in committed files.
// Runs automatically before `npm start`, `npm run build` and `npm test`. Real environment variables win over .env,
// so a build server can pass them without a file. Copy .env.example to .env to get started.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src', 'environments', 'env.generated.ts');

/** KEY=value lines; # comments and blank lines ignored; optional quotes removed. */
function parse(text) {
  const values = {};
  for (const line of text.split(/\r?\n/)) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
    if (!match || line.trimStart().startsWith('#')) continue;
    values[match[1]] = match[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  return values;
}

const file = join(root, '.env');
const fromFile = existsSync(file) ? parse(readFileSync(file, 'utf8')) : {};
const get = (name, fallback) => process.env[name] ?? fromFile[name] ?? fallback;

const env = {
  apiBaseUrl: get('NG_APP_API_BASE_URL', 'http://localhost:5001/api').replace(/\/+$/, ''),
  // Browser key for drawing the Google map only (Maps JavaScript API). Restrict it to your site's address in
  // Google Cloud Console. Empty = the site uses OpenStreetMap. Places, routes and photos go through the backend.
  googleMapsApiKey: get('NG_APP_GOOGLE_MAPS_API_KEY', ''),
  googleMapId: get('NG_APP_GOOGLE_MAP_ID', 'DEMO_MAP_ID'),
  // Client credentials, swapped for a short-lived client token that every API request carries.
  clientId: get('NG_APP_CLIENT_ID', 'yaal-web'),
  clientSecret: get('NG_APP_CLIENT_SECRET', '')
};

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/set-env.mjs from .env — do not edit or commit.\nexport const ENV = ${JSON.stringify(env, null, 2)} as const;\n`
);
console.log(`env: API ${env.apiBaseUrl}; Google map ${env.googleMapsApiKey ? 'key set' : 'not set (OpenStreetMap)'}`);
